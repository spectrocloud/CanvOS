#!/bin/bash
# Unit tests for overlay/kdump/ubuntu/usr/lib/kdump/kdump-merge (bash and coreutils only).
#
# Every case gives kdump-merge its own defaults, override and output files (KDUMP_DEFAULTS,
# KDUMP_OVERRIDE, KDUMP_CONF) and its reservation inputs (KDUMP_CRASH_SIZE_FILE, KDUMP_VMCORE_FILE,
# KDUMP_RECOVERY_FILE) inside a temporary directory, so nothing outside it is read or written.
#
#   bash test/kdump-merge_test.sh
#   docker run --rm -v "$PWD":/src ubuntu:24.04 bash /src/test/kdump-merge_test.sh

set -u
REPO_ROOT="$(cd "$(dirname "$0")/.." && pwd)"
M="$REPO_ROOT/overlay/kdump/ubuntu/usr/lib/kdump/kdump-merge"
SRC="$REPO_ROOT/overlay/kdump/ubuntu/etc/default/kdump-tools.default"
REQ="reset_devices systemd.unit=kdump-tools-dump.service nr_cpus=1 irqpoll usbcore.nousb kho=off"

WORK="$(mktemp -d)"
chmod 755 "$WORK"
trap 'chmod -R u+w "$WORK" 2>/dev/null; rm -rf "$WORK"' EXIT

PASS=0
FAIL=0

ok() {
    if eval "$2"; then
        PASS=$((PASS + 1)); echo "PASS $1"
    else
        FAIL=$((FAIL + 1)); echo "FAIL $1"
        grep -v '^#' "$D/conf" 2>/dev/null | grep .
        head -2 "$D/conf" 2>/dev/null
        cat "$D/log" 2>/dev/null
    fi
}
new() { D="$(mktemp -d "$WORK/case.XXXXXX")"; cp "$SRC" "$D/def"; cp "$D/def" "$D/conf"; }
merge() { KDUMP_DEFAULTS="$D/def" KDUMP_CONF="$D/conf" KDUMP_OVERRIDE="$D/ov" bash "$M" > "$D/log" 2>&1; echo $? > "$D/rc"; }
ov() { printf '%s' "$1" > "$D/ov"; }
get() { (. "$D/conf"; eval "printf '%s' \"\$$1\""); }
clean() { [ -z "$(grep -vE '^((#|[A-Z_][A-Z0-9_]*=).*)?$' "$D/conf")" ]; }

[ -f "$M" ] && [ -f "$SRC" ] || { echo "kdump-merge or the defaults file is missing under $REPO_ROOT/overlay/kdump/ubuntu"; exit 1; }

# --- merge -----------------------------------------------------------------------------------------

new; merge
ok "no override -> defaults"             '[ "$(get KDUMP_NUM_DUMPS)" = 3 ] && [ "$(get KDUMP_CMDLINE_APPEND)" = "$REQ" ] && clean && grep -q "overrides from none" "$D/log" && grep -q "^# Generated by" "$D/conf"'
new; ov $'KDUMP_NUM_DUMPS=2\nKDUMP_DUMP_DMESG=0\nKDUMP_CMDLINE_APPEND="loglevel=7"\n'; merge
ok "overrides applied, extras first"     '[ "$(get KDUMP_NUM_DUMPS)/$(get KDUMP_DUMP_DMESG)" = 2/0 ] && [ "$(get KDUMP_CMDLINE_APPEND)" = "loglevel=7 $REQ" ] && clean && sh -c ". $D/conf"'
ok "defaults file untouched"             'cmp -s "$D/def" "$SRC" && [ "$(grep -c "^# Generated by" "$D/conf")" = 1 ]'
cp "$D/conf" "$D/first"; merge
ok "second merge identical"              'cmp -s "$D/conf" "$D/first"'
ov $'KDUMP_CMDLINE_APPEND="loglevel=4"\n'; merge
ok "changed and removed keys revert"     '[ "$(get KDUMP_CMDLINE_APPEND)" = "loglevel=4 $REQ" ] && [ "$(get KDUMP_NUM_DUMPS)" = 3 ] && [ "$(get KDUMP_DUMP_DMESG)" = 1 ]'
rm "$D/ov"; merge
ok "removed file -> defaults"            'cmp -s <(grep -v "^# Generated" "$D/conf") "$D/def"'
new; ov $'KDUMP_CMDLINE_APPEND="loglevel=7 loglevel=7 nr_cpus=1 kho=off quiet quiet"\n'; merge
ok "duplicates removed"                  '[ "$(get KDUMP_CMDLINE_APPEND)" = "loglevel=7 quiet $REQ" ]'
new; ov $'KDUMP_NUM_DUMPS=99\nKDUMP_DUMP_DMESG=yes\nKDUMP_CMDLINE_APPEND="systemd.unit=rescue.target kho=on nr_cpus=4 loglevel=7 $(reboot) root=/dev/sda"\nKDUMP_COREDIR=/var/crash\nMAKEDUMP_ARGS="-d 0"\nUSE_KDUMP=0\nKDUMP_KERNEL=/x\nFOO=1\ngarbage\n'; merge
ok "bad overrides rejected, exit 0"      '[ "$(get KDUMP_NUM_DUMPS)/$(get KDUMP_DUMP_DMESG)/$(get USE_KDUMP)" = 3/1/1 ] && [ "$(get KDUMP_COREDIR)" = /usr/local/kdump ] && [ "$(get MAKEDUMP_ARGS)" = "-F -c -d 31" ] && [ "$(get KDUMP_CMDLINE_APPEND)" = "loglevel=7 $REQ" ] && [ "$(grep -c WARNING "$D/log")" -eq 13 ] && [ "$(cat "$D/rc")" = 0 ] && clean && grep -q "^# Rejected:" "$D/conf"'
new; ov "$(printf 'KDUMP_CMDLINE_APPEND="a$(touch %s/pwned-sub) b`touch %s/pwned-tick` c"\nKDUMP_NUM_DUMPS=$(touch %s/pwned-num)\n' "$WORK" "$WORK" "$WORK")"; merge
ok "override text is never executed"     '[ ! -e "$WORK/pwned-sub" ] && [ ! -e "$WORK/pwned-tick" ] && [ ! -e "$WORK/pwned-num" ] && [ "$(get KDUMP_NUM_DUMPS)" = 3 ] && [ "$(cat "$D/rc")" = 0 ] && clean'
new; ov $'# c\n\n  KDUMP_NUM_DUMPS=5  \r\n'; merge
ok "comments, CRLF and spaces"           '[ "$(get KDUMP_NUM_DUMPS)" = 5 ]'

# --- failure handling: kdump-merge always exits 0 and never leaves a broken file -------------------

new; rm "$D/def"; cp "$D/conf" "$D/before"; merge
ok "defaults missing -> conf unchanged"  'cmp -s "$D/conf" "$D/before" && grep -q "is missing" "$D/log" && [ "$(cat "$D/rc")" = 0 ]'
new; echo "STALE_KEY=1" > "$D/conf"; merge
ok "stale conf replaced"                 '! grep -q STALE_KEY "$D/conf" && grep -q "^# Generated by" "$D/conf" && [ "$(cat "$D/rc")" = 0 ]'
new; rm -f "$D/conf"; merge
ok "no conf before -> generated"         '[ -s "$D/conf" ] && [ "$(get KDUMP_NUM_DUMPS)" = 3 ] && [ "$(cat "$D/rc")" = 0 ]'
# The plain copy of the defaults succeeds, the merged write fails (mktemp broken): the copy stays.
new; ov $'KDUMP_NUM_DUMPS=2\n'; echo "STALE_KEY=1" > "$D/conf"; mkdir -p "$D/bin"; printf '#!/bin/sh\nexit 1\n' > "$D/bin/mktemp"; chmod +x "$D/bin/mktemp"
PATH="$D/bin:$PATH" KDUMP_DEFAULTS="$D/def" KDUMP_CONF="$D/conf" KDUMP_OVERRIDE="$D/ov" bash "$M" > "$D/log" 2>&1; echo $? > "$D/rc"
ok "merge fails -> defaults stay"        'cmp -s "$D/conf" "$D/def" && grep -q "cannot write" "$D/log" && [ "$(cat "$D/rc")" = 0 ]'
# File permissions do not stop root, so the unwritable case needs another user.
if [ "$(id -u)" -eq 0 ] && id nobody > /dev/null 2>&1; then
    D="$(mktemp -d "$WORK/case.XXXXXX")"; cp "$SRC" "$D/def"; cp "$D/def" "$D/conf"; chmod 444 "$D/conf"; chmod 555 "$D"
    out="$(su nobody -s /bin/bash -c "KDUMP_DEFAULTS=$D/def KDUMP_CONF=$D/conf KDUMP_OVERRIDE=/nonexistent bash $M" 2>&1)"; rc=$?
    ok "unwritable -> exit 0, unchanged" '[ "$rc" = 0 ] && grep -q "leaving" <<<"$out" && cmp -s "$D/conf" "$D/def"'
else
    echo "SKIP unwritable -> exit 0, unchanged (needs root to switch user)"
fi

# --- --reserved (the ExecCondition of kdump-tools.service) ----------------------------------------

R() { KDUMP_RECOVERY_FILE="${3:-/nonexistent}" KDUMP_CRASH_SIZE_FILE="$1" KDUMP_VMCORE_FILE="$2" bash "$M" --reserved > "$WORK/r.log" 2>&1; echo $?; }
echo 536870912 > "$WORK/cs1"; echo 0 > "$WORK/cs0"; touch "$WORK/vmcore" "$WORK/recovery"; mkdir -p "$WORK/unreadable"
ok "reserved -> 0"                       '[ "$(R "$WORK/cs1" /nonexistent)" = 0 ]'
ok "not reserved -> 1 and why"           '[ "$(R "$WORK/cs0" /nonexistent)" = 1 ] && grep -q "no crash kernel memory reserved" "$WORK/r.log"'
ok "no kexec support -> 1"               '[ "$(R /nonexistent /nonexistent)" = 1 ]'
ok "capture boot -> 0"                   '[ "$(R "$WORK/cs0" "$WORK/vmcore")" = 0 ]'
ok "unreadable size (EBUSY-like) -> 0"   '[ "$(R "$WORK/unreadable" /nonexistent)" = 0 ]'
ok "recovery system -> 1 and why"        '[ "$(R "$WORK/cs1" /nonexistent "$WORK/recovery")" = 1 ] && grep -q "kdump off: recovery system" "$WORK/r.log"'
ok "recovery, nothing reserved -> 1"     '[ "$(R "$WORK/cs0" /nonexistent "$WORK/recovery")" = 1 ] && grep -q "recovery system" "$WORK/r.log"'
ok "recovery + capture boot -> 0"        '[ "$(R "$WORK/cs1" "$WORK/vmcore" "$WORK/recovery")" = 0 ]'
ok "no recovery marker, reserved -> 0"   '[ "$(R "$WORK/cs1" /nonexistent /nonexistent)" = 0 ]'

echo "----------------------------------------"
echo "PASS: $PASS   FAIL: $FAIL"
[ "$FAIL" -eq 0 ]
